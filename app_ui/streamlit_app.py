api_url = st.sidebar.text_input("Backend API Base URL", value=DEFAULT_API_URL)
api_key = st.sidebar.text_input("API Key", value=DEFAULT_API_KEY, type="password")

# Check API Health
headers = {"X-API-Key": api_key, "Content-Type": "application/json"}
api_healthy = False
try:
    resp = requests.get(f"{api_url}/health", timeout=3)
    if resp.status_code == 200:
        api_healthy = True
        st.sidebar.success("Backend API: Connected (200 OK)")
    else:
        st.sidebar.warning(f"Backend API status: {resp.status_code}")
except Exception:
    st.sidebar.error("Backend API: Offline / Unreachable")

st.markdown('<div class="main-header">Real-Time Fraud Scoring Dashboard</div>', unsafe_allow_html=True)
