with tab1:
    col_preset, col_empty = st.columns([2, 2])
    with col_preset:
        selected_preset = st.selectbox("Load Sample Preset Transaction:", ["Custom Entry"] + list(PRESETS.keys()))

    preset_data = PRESETS.get(selected_preset, PRESETS["Low-Risk Card Purchase"])

    with st.form("single_tx_form"):
        col1, col2, col3 = st.columns(3)
        with col1:
            tx_id = st.text_input("Transaction ID", value=preset_data.get("transaction_id", "tx_demo_001"))
            tx_dt = st.number_input("Transaction DT (seconds)", value=int(preset_data.get("TransactionDT", 86400)))
            tx_amt = st.number_input("Transaction Amount ($)", value=float(preset_data.get("TransactionAmt", 100.0)), min_value=0.01)
            prod_cd = st.selectbox("Product Code (ProductCD)", ["W", "C", "R", "H", "S"], index=["W", "C", "R", "H", "S"].index(preset_data.get("ProductCD", "W")))

        with col2:
            card1 = st.number_input("Card 1 (Issuer)", value=int(preset_data.get("card1", 1000)))
            card2 = st.number_input("Card 2", value=float(preset_data.get("card2", 500.0)))
            card4 = st.selectbox("Card Brand (card4)", ["visa", "mastercard", "discover", "american express"], index=0)
            card6 = st.selectbox("Card Type (card6)", ["debit", "credit"], index=0)

        with col3:
            p_email = st.text_input("Purchaser Email Domain", value=preset_data.get("P_emaildomain", "gmail.com"))
            r_email = st.text_input("Recipient Email Domain", value=preset_data.get("R_emaildomain", "gmail.com"))
            dev_type = st.selectbox("Device Type", ["desktop", "mobile"], index=0)
            dev_info = st.text_input("Device Info", value=preset_data.get("DeviceInfo", "Windows"))

        explain_toggle = st.checkbox("Return SHAP Feature Reasons", value=True)
        submit_btn = st.form_submit_button("🛡️ Score Transaction Now", use_container_width=True)

    if submit_btn:
        payload = {
            "transaction_id": tx_id,
            "TransactionDT": tx_dt,
            "TransactionAmt": tx_amt,
            "ProductCD": prod_cd,
            "card1": card1,
            "card2": card2,
            "card4": card4,
            "card6": card6,
            "P_emaildomain": p_email,
            "R_emaildomain": r_email,
            "DeviceType": dev_type,
            "DeviceInfo": dev_info,
        }

        try:
            t0 = time.time()
            score_url = f"{api_url}/v1/score?explain={str(explain_toggle).lower()}"
            res = requests.post(score_url, headers=headers, json=payload, timeout=10)
            elapsed_ms = round((time.time() - t0) * 1000, 2)

            if res.status_code == 200:
                data = res.json()
                prob = data["fraud_probability"]
                decision = data["decision"]
                risk_band = data["risk_band"]
                reasons = data.get("reasons", [])

                st.markdown("---")
                st.subheader("🎯 Scoring Results")

                res_col1, res_col2, res_col3, res_col4 = st.columns(4)
                with res_col1:
                    st.metric("Calibrated Fraud Probability", f"{prob:.4f} ({prob*100:.2f}%)")
                with res_col2:
                    if decision == "approve":
                        st.markdown('Decision: <div class="badge-approve">APPROVE</div>', unsafe_allow_html=True)
                    elif decision == "review":
                        st.markdown('Decision: <div class="badge-review">MANUAL REVIEW</div>', unsafe_allow_html=True)
                    else:
                        st.markdown('Decision: <div class="badge-block">BLOCK</div>', unsafe_allow_html=True)
                with res_col3:
                    st.metric("Risk Band", risk_band)
                with res_col4:
                    st.metric("API Latency", f"{elapsed_ms} ms")

                st.progress(prob)

                # Reasons Visualization
                if reasons:
                    st.subheader("🔍 Top 5 Per-Prediction Reason Codes (SHAP Contributions)")
                    rdf = pd.DataFrame(reasons)

                    fig, ax = plt.subplots(figsize=(8, 3.5))
                    colors = ["#E53935" if d == "increases_risk" else "#43A047" for d in rdf["direction"]]
                    bars = ax.barh(rdf["label"], rdf["contribution"], color=colors)
                    ax.axvline(0, color="gray", linewidth=0.8, linestyle="--")
                    ax.set_xlabel("SHAP Contribution to Fraud Score")
                    ax.set_title("Feature Contribution Breakdown")
                    ax.invert_yaxis()
                    plt.tight_layout()
                    st.pyplot(fig)

                    st.dataframe(rdf[["label", "value", "contribution", "direction"]], use_container_width=True)

            else:
                st.error(f"API Error {res.status_code}: {res.text}")
        except Exception as err:
            st.error(f"Connection Error: Could not reach scoring API at {api_url}. Error: {err}")

with tab2:
    st.subheader("📦 Batch Transaction Scoring")
    st.write("Score up to 1,000 transactions simultaneously in high-throughput mode.")

    sample_batch = [PRESETS["Low-Risk Card Purchase"], PRESETS["High-Risk Crypto/Cross-Border"], PRESETS["Medium-Risk Manual Review"]]
    json_batch_input = st.text_area("JSON Batch Input:", value=json.dumps({"transactions": sample_batch}, indent=2), height=250)

    if st.button("🚀 Score Batch Transactions", use_container_width=True):
        try:
            batch_payload = json.loads(json_batch_input)
            res = requests.post(f"{api_url}/v1/score/batch?explain=false", headers=headers, json=batch_payload, timeout=15)
            if res.status_code == 200:
                bdata = res.json()
                st.success(f"Batch Processed {bdata['total_processed']} transactions in {bdata['batch_latency_ms']} ms")
                results_df = pd.DataFrame(bdata["results"])
                st.dataframe(results_df, use_container_width=True)
            else:
                st.error(f"Batch Error {res.status_code}: {res.text}")
        except Exception as e:
            st.error(f"Invalid JSON or Request Error: {e}")

with tab3:
    st.subheader("📊 Model Information & Threshold Configuration")
    try:
        minfo_res = requests.get(f"{api_url}/v1/model/info", headers=headers, timeout=5)
        if minfo_res.status_code == 200:
            minfo = minfo_res.json()
            st.json(minfo)
        else:
            st.warning("Model info endpoint returned non-200 status.")
    except Exception as e:
        st.error(f"Could not retrieve model info: {e}")
